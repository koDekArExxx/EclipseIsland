const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('island', {
  launcherProcesses:()=>ipcRenderer.invoke('launcher:processes'),
  focusInput:value=>ipcRenderer.send('island:focus-input',value),
  launcher:(action,id,value)=>ipcRenderer.invoke('launcher:action',action,id,value),
  screenshot:(action,id)=>ipcRenderer.invoke('screenshot:action',action,id),
  toolsSettings:patch=>ipcRenderer.invoke('desktop-tools:save',patch),
  screenshotFolder:()=>ipcRenderer.invoke('screenshot:folder'),
  ayuFolder:()=>ipcRenderer.invoke('downloads:ayu-folder'),
  downloads:(action,id)=>ipcRenderer.invoke('downloads:action',action,id),
  transfer:(action,id)=>ipcRenderer.invoke('transfers:action',action,id),
  activityHeartbeat:ids=>ipcRenderer.send('activities:heartbeat',ids),
  capture: (action,id) => ipcRenderer.invoke('capture:action',action,id),
  captureSettings: patch => ipcRenderer.invoke('capture:save',patch),
  captureSources: () => ipcRenderer.invoke('capture:sources'),
  captureFolder: () => ipcRenderer.invoke('capture:folder'),
  init: () => ipcRenderer.invoke('init'),
  save: settings => ipcRenderer.invoke('settings:save', settings),
  cities: query => ipcRenderer.invoke('weather:search', query),
  selectCity: city => ipcRenderer.invoke('weather:select', city),
  refreshWeather: () => ipcRenderer.invoke('weather:refresh'),
  mediaApplied: sequence => ipcRenderer.send('media:applied',sequence),
  spotifySetupLog: () => ipcRenderer.invoke('spotify:setup-log'),
  setupSpotify: () => ipcRenderer.invoke('spotify:setup'),
  mediaDiagnostics: () => ipcRenderer.invoke('media:diagnostics'),
  media: (action, seconds) => ipcRenderer.invoke('media:command', action, seconds),
  showSettings: page => ipcRenderer.send('settings:show',page),
  minimize: () => ipcRenderer.send('window:minimize'),
  close: () => ipcRenderer.send('window:close'),
  quit: () => ipcRenderer.send('app:quit'),
  bounds: rect => ipcRenderer.send('island:bounds', rect),
  on: callback => { const listener = (_,message) => callback(message);ipcRenderer.on('state',listener);return () => ipcRenderer.removeListener('state',listener); }
});
